"""Convert a Course Edit design icon PNG into a stock N64 I4 texture and write it as a C source file.

Usage, from the repository root (the PNG is read only):

    python -I tools/gen_course_edit_tex.py port/assets/course_edit/aCourseEditInsertTex.png port/gdx_course_edit_insert_tex.c
    python -I tools/gen_course_edit_tex.py port/assets/course_edit/aCourseEditSplitTex.png port/gdx_course_edit_split_tex.c
    python -I tools/gen_course_edit_tex.py port/assets/course_edit/aCourseEditLinkTex.png port/gdx_course_edit_link_tex.c

The C symbol is the PNG file name without its extension, so aCourseEditLinkTex.png defines
aCourseEditLinkTex.

Each pixel's 4-bit intensity comes from its alpha channel, because the RGB values of transparent
pixels are arbitrary. Pixels are packed the way the stock G_IM_FMT_I, G_IM_SIZ_4b textures are:
rows run top to bottom, 24 bytes per 48-pixel row, and the high nibble of each byte is the left
pixel of the pair. libultraship decodes the same layout in ImportTextureI4 and expands each
intensity to alpha with SCALE_4_8 (value * 17), so alpha values that are multiples of 17 round
trip exactly.
"""

import hashlib
import os
import sys

from PIL import Image

WIDTH = 48
HEIGHT = 16
BYTES_PER_ROW = WIDTH // 2
TEXTURE_BYTES = BYTES_PER_ROW * HEIGHT
VALUES_PER_LINE = 12
SYMBOL_PREFIX = "aCourseEdit"
SYMBOL_SUFFIX = "Tex"


def intensity_from_alpha(alpha):
    """Map alpha 0..255 to a 4-bit intensity 0..15. Exact when alpha is a multiple of 17."""
    return (alpha * 15 + 127) // 255


def pack_texture(rgba):
    """Pack an RGBA image into the 384-byte I4 layout. Returns (bytes, inexact pixel count)."""
    packed = bytearray()
    inexact = 0
    for y in range(HEIGHT):
        for x in range(0, WIDTH, 2):
            pair = []
            for px in (x, x + 1):
                alpha = rgba.getpixel((px, y))[3]
                nibble = intensity_from_alpha(alpha)
                if nibble * 17 != alpha:
                    inexact += 1
                pair.append(nibble)
            packed.append((pair[0] << 4) | pair[1])
    return bytes(packed), inexact


def render_c(packed, symbol, source_name, source_sha256):
    label = symbol[len(SYMBOL_PREFIX):-len(SYMBOL_SUFFIX)].upper()
    lines = [
        "/* Course Edit %s design icon: stock I4 48x16 texture (384 bytes)." % label,
        " * Generated by tools/gen_course_edit_tex.py from %s." % source_name,
        " * Source sha256: %s" % source_sha256,
        " * Do not edit by hand; regenerate it from the PNG instead. */",
        "",
        "unsigned char %s[%d] = {" % (symbol, TEXTURE_BYTES),
    ]
    for y in range(HEIGHT):
        row = packed[y * BYTES_PER_ROW:(y + 1) * BYTES_PER_ROW]
        lines.append("    /* row %d */" % y)
        for start in range(0, len(row), VALUES_PER_LINE):
            chunk = row[start:start + VALUES_PER_LINE]
            lines.append("    " + ", ".join("0x%02X" % value for value in chunk) + ",")
    lines.append("};")
    lines.append("")
    return "\n".join(lines)


def main(argv):
    if len(argv) != 3:
        sys.stderr.write("usage: python -I tools/gen_course_edit_tex.py <input.png> <output.c>\n")
        return 2
    png_path, out_path = argv[1], argv[2]
    symbol = os.path.splitext(os.path.basename(png_path))[0]
    if (not symbol.startswith(SYMBOL_PREFIX) or not symbol.endswith(SYMBOL_SUFFIX)
            or len(symbol) <= len(SYMBOL_PREFIX) + len(SYMBOL_SUFFIX) or not symbol.isalnum()):
        sys.stderr.write("error: the PNG must be named %s<Name>%s.png\n" % (SYMBOL_PREFIX, SYMBOL_SUFFIX))
        return 2

    with open(png_path, "rb") as handle:
        source_bytes = handle.read()
    with Image.open(png_path) as image:
        rgba = image.convert("RGBA")
    if rgba.size != (WIDTH, HEIGHT):
        sys.stderr.write("error: expected %dx%d, got %dx%d\n" % (WIDTH, HEIGHT, rgba.size[0], rgba.size[1]))
        return 1

    packed, inexact = pack_texture(rgba)
    text = render_c(packed, symbol, os.path.basename(png_path), hashlib.sha256(source_bytes).hexdigest())
    with open(out_path, "w", encoding="ascii", newline="\n") as handle:
        handle.write(text)
    print("wrote %d bytes to %s; pixels whose alpha is not a multiple of 17: %d"
          % (len(packed), out_path, inexact))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
