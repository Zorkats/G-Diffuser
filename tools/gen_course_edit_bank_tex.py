"""Convert the Course Edit bank snap icon PNGs into stock N64 RGBA16 textures and write them as C source.

Usage, from the repository root (the PNGs are read only):

    python -I tools/gen_course_edit_bank_tex.py port/gdx_course_edit_bank_tex.c \
        port/assets/course_edit/aCourseEditBank45IconTex.png \
        port/assets/course_edit/aCourseEditBank90IconTex.png \
        port/assets/course_edit/aCourseEditBank180IconTex.png

Each C symbol is the PNG file name without its extension.

The PNGs are hollow circles with soft edges, and RGBA16 only has one bit of alpha. So each icon is
blended over a gold plate drawn here, which also lets it sit in the icon row like the gold grid
button. Pixels are RGBA5551 with rows running top to bottom, stored as big-endian bytes the way the
ROM stores them and libultraship's ImportTextureRgba16 reads them.
"""

import hashlib
import os
import sys

from PIL import Image

SIZE = 16
TEXTURE_BYTES = SIZE * SIZE * 2
VALUES_PER_LINE = 12
SYMBOL_PREFIX = "aCourseEdit"
SYMBOL_SUFFIX = "Tex"

PLATE_TOP = (0x59, 0x26, 0x00)
PLATE_BOTTOM = (0x29, 0x07, 0x00)
PLATE_LEFT = (0xE9, 0xD0, 0x0F)
PLATE_RIGHT = (0x65, 0x29, 0x00)
PLATE_BODY_TOP = (0xD9, 0x87, 0x00)
PLATE_BODY_BOTTOM = (0xE8, 0xAC, 0x00)


def plate_color(x, y):
    """The gold plate: one-pixel bevel around a vertical gradient."""
    if y == 0:
        return PLATE_TOP
    if y == SIZE - 1:
        return PLATE_BOTTOM
    if x == 0:
        return PLATE_LEFT
    if x == SIZE - 1:
        return PLATE_RIGHT
    t = (y - 1) / (SIZE - 3)
    return tuple(round(a + (b - a) * t) for a, b in zip(PLATE_BODY_TOP, PLATE_BODY_BOTTOM))


def to_rgba5551(rgb):
    r, g, b = ((channel * 31 + 127) // 255 for channel in rgb)
    return (r << 11) | (g << 6) | (b << 1) | 1


def pack_texture(rgba):
    """Blend an RGBA image over the plate and pack it into 512 big-endian RGBA5551 bytes."""
    packed = bytearray()
    for y in range(SIZE):
        for x in range(SIZE):
            r, g, b, a = rgba.getpixel((x, y))
            blended = [(c * a + p * (255 - a) + 127) // 255 for c, p in zip((r, g, b), plate_color(x, y))]
            pixel = to_rgba5551(blended)
            packed.append(pixel >> 8)
            packed.append(pixel & 0xFF)
    return bytes(packed)


def render_array(packed, symbol, source_name, source_sha256):
    lines = [
        "/* Generated from %s. Source sha256: %s */" % (source_name, source_sha256),
        "unsigned char %s[%d] = {" % (symbol, TEXTURE_BYTES),
    ]
    for y in range(SIZE):
        row = packed[y * SIZE * 2:(y + 1) * SIZE * 2]
        lines.append("    /* row %d */" % y)
        for start in range(0, len(row), VALUES_PER_LINE):
            chunk = row[start:start + VALUES_PER_LINE]
            lines.append("    " + ", ".join("0x%02X" % value for value in chunk) + ",")
    lines.append("};")
    lines.append("")
    return lines


def main(argv):
    if len(argv) < 3:
        sys.stderr.write("usage: python -I tools/gen_course_edit_bank_tex.py <output.c> <input.png>...\n")
        return 2
    out_path = argv[1]
    lines = [
        "/* Course Edit bank snap icons: stock RGBA16 16x16 textures (512 bytes each).",
        " * Generated by tools/gen_course_edit_bank_tex.py; icon art by Heebeejeebees.",
        " * Do not edit by hand; regenerate it from the PNGs instead. */",
        "",
    ]
    for png_path in argv[2:]:
        symbol = os.path.splitext(os.path.basename(png_path))[0]
        if not symbol.startswith(SYMBOL_PREFIX) or not symbol.endswith(SYMBOL_SUFFIX) or not symbol.isalnum():
            sys.stderr.write("error: the PNG must be named %s<Name>%s.png\n" % (SYMBOL_PREFIX, SYMBOL_SUFFIX))
            return 2
        with open(png_path, "rb") as handle:
            source_bytes = handle.read()
        with Image.open(png_path) as image:
            rgba = image.convert("RGBA")
        if rgba.size != (SIZE, SIZE):
            sys.stderr.write("error: %s: expected %dx%d, got %dx%d\n"
                             % (png_path, SIZE, SIZE, rgba.size[0], rgba.size[1]))
            return 1
        lines += render_array(pack_texture(rgba), symbol, os.path.basename(png_path),
                              hashlib.sha256(source_bytes).hexdigest())
    with open(out_path, "w", encoding="ascii", newline="\n") as handle:
        handle.write("\n".join(lines))
    print("wrote %d textures to %s" % (len(argv) - 2, out_path))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
