
#pragma once
#include <array>
#include <cstdint>
enum SDL_GameControllerButton { SDL_CONTROLLER_BUTTON_A, SDL_CONTROLLER_BUTTON_B, SDL_CONTROLLER_BUTTON_X,
 SDL_CONTROLLER_BUTTON_Y, SDL_CONTROLLER_BUTTON_BACK, SDL_CONTROLLER_BUTTON_GUIDE, SDL_CONTROLLER_BUTTON_START,
 SDL_CONTROLLER_BUTTON_LEFTSTICK, SDL_CONTROLLER_BUTTON_RIGHTSTICK, SDL_CONTROLLER_BUTTON_LEFTSHOULDER,
 SDL_CONTROLLER_BUTTON_RIGHTSHOULDER, SDL_CONTROLLER_BUTTON_DPAD_UP, SDL_CONTROLLER_BUTTON_DPAD_DOWN,
 SDL_CONTROLLER_BUTTON_DPAD_LEFT, SDL_CONTROLLER_BUTTON_DPAD_RIGHT, SDL_CONTROLLER_BUTTON_MISC1,
 SDL_CONTROLLER_BUTTON_PADDLE1, SDL_CONTROLLER_BUTTON_PADDLE2, SDL_CONTROLLER_BUTTON_PADDLE3,
 SDL_CONTROLLER_BUTTON_PADDLE4, SDL_CONTROLLER_BUTTON_MAX };
enum SDL_GameControllerAxis { SDL_CONTROLLER_AXIS_LEFTX, SDL_CONTROLLER_AXIS_LEFTY, SDL_CONTROLLER_AXIS_RIGHTX,
 SDL_CONTROLLER_AXIS_RIGHTY, SDL_CONTROLLER_AXIS_TRIGGERLEFT, SDL_CONTROLLER_AXIS_TRIGGERRIGHT, SDL_CONTROLLER_AXIS_MAX };
constexpr int SDL_JOYSTICK_AXIS_MAX = 32767;
struct SDL_GameController { bool attached = true; std::array<bool, SDL_CONTROLLER_BUTTON_MAX> buttons{};
 std::array<int16_t, SDL_CONTROLLER_AXIS_MAX> axes{}; };
inline bool SDL_GameControllerGetAttached(SDL_GameController* pad) { return pad->attached; }
inline bool SDL_GameControllerGetButton(SDL_GameController* pad, SDL_GameControllerButton button) {
 return pad->attached && pad->buttons[button]; }
inline int16_t SDL_GameControllerGetAxis(SDL_GameController* pad, SDL_GameControllerAxis axis) {
 return pad->attached ? pad->axes[axis] : 0; }
